def _find_datafile() -> str:
    """datafile.py is the storage engine. Locate it without vendoring a copy."""
    here = os.path.dirname(os.path.abspath(__file__))
    cands = [os.environ.get("TASKS_DATAFILE"),
             os.path.join(here, "datafile.py"),
             os.path.join(here, os.pardir, "datafile", "datafile.py")]
    found = shutil.which("datafile") or shutil.which("datafile.py")
    if found:
        cands.append(os.path.realpath(found))
    for c in cands:
        if c and os.path.isfile(c):
            return os.path.abspath(c)
    return ""


