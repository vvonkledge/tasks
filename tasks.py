def cmd_pi_package(args) -> int:
    uv = shutil.which("uv")
    if not uv:
        raise df.AxiError("uv not found on PATH", "SETUP_ERROR",
                          [f"Install uv, then re-run `{PROG} pi-package`"], exit_code=1)
    root = args.out or PI_PACKAGE_DIR
    files = _pi_files([*df._hook_argv(uv, os.path.abspath(__file__)), AMBIENT_FLAG])
    stale = [rel for rel, want in files.items()
             if df._read_text(os.path.join(root, rel)) != want]

    if args.check:
        if stale:
            raise df.AxiError(f"{df.collapse_home(root)} is out of date", "PACKAGE_STALE",
                              [f"Run `{PROG} pi-package` to regenerate it"],
                              exit_code=1, extra={"stale": sorted(stale)})
        df.emit({"package": f"{df.collapse_home(root)} is up to date"})
        return 0

    if not stale:
        df.emit({"package": f"{df.collapse_home(root)} unchanged (no-op)"})
        return 0
    for rel, want in files.items():
        df._write(os.path.join(root, rel), want)
    df.emit({"package": df.collapse_home(root), "files": sorted(files),
             "help": [f"Run `pi install {os.path.abspath(root)}` to install it",
                      f"Run `{PROG} pi-package --check` to catch drift on this "
                      f"machine (it bakes in an absolute path, so it fails elsewhere)"]})
    return 0


