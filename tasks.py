# ----------------------------------------------------------------- primitives

def _now() -> str:
    return datetime.now(UTC).isoformat()


def _age(dt: datetime) -> str:
    if dt.tzinfo is None:                      # hand-edited row: assume UTC
        dt = dt.replace(tzinfo=UTC)
    secs = (datetime.now(UTC) - dt).total_seconds()
    if secs < 3600:
        return f"{max(0, int(secs // 60))}m"
    if secs < 86400:
        return f"{int(secs // 3600)}h"
    return f"{int(secs // 86400)}d"


def _aware(dt: datetime) -> datetime:
    """Sorting mixes stored rows with hand-edited ones, and Python refuses to
    compare a naive datetime with an aware one. The view that runs on every
    session start must not be the thing that raises."""
    return dt.replace(tzinfo=UTC) if dt.tzinfo is None else dt


def _days(dt: datetime) -> float:
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=UTC)
    return (datetime.now(UTC) - dt).total_seconds() / 86400


def _slug(title: str, taken) -> str:
    """Ids are derived from the title, never invented by the caller: the id is
    then self-describing in every later output."""
    words = [w for w in re.split(r"[^a-z0-9]+", title.lower()) if w]
    s = ""
    for w in words:                            # whole words up to the budget
        if s and len(s) + 1 + len(w) > SLUG_BUDGET:
            break
        s = f"{s}-{w}" if s else w
    parts = s.split("-")
    while len(parts) > 1 and parts[-1] in SLUG_STOP:   # never end on a stopword
        parts.pop()
    s = "-".join(parts)
    if not s or not s[0].isalpha():
        s = "t-" + s if s else "task"
    s = s[:48]
    while len(s) < 3:
        s += "-t"
    if s not in taken:
        return s
    for n in range(2, 1000):
        cand = f"{s[:48 - len(str(n)) - 1]}-{n}"
        if cand not in taken:
            return cand
    raise df.AxiError(f"cannot derive a free id from {title!r}", "ID_EXHAUSTED",
                      exit_code=2)


def _open(args):
    path = getattr(args, "file", None) or STORE
    cpath = df.find_contract(path)
    if not cpath:
        raise df.AxiError(
            f"no contract found for {path}", "NO_CONTRACT",
            [f"Run `{PROG} init` to create schema-tasks.yaml beside it"],
            exit_code=1)
    model, key = df.load_contract(cpath)
    return df.Store(path, model, key)


def _need(store, rid: str):
    t = store.get(rid)
    if t is None:
        raise df.AxiError(f"task not found: {rid}", "NOT_FOUND",
                          [f"Run `{PROG} list` to see task ids"], exit_code=1)
    return t


def _save(store, task, **changes):
    d = task.model_dump(mode="json")
    d.update(changes)
    d["updated"] = _now()
    return store.put(d)


def _guard_in_flight(t, force: bool, action: str) -> None:
    """A task in `doing` belongs to its owner; the orchestrator treats it as
    read-only. Turns a silent lost update into a loud error."""
    if t.status == "doing" and not force:
        raise df.AxiError(
            f"{t.id} is in flight, owned by {t.owner or 'unknown'}",
            "TASK_IN_FLIGHT",
            [f"Run `{PROG} {action} --force` to override the owner",
             f"Run `{PROG} reset {t.id} --reason \"<why>\"` to reclaim it first"],
            exit_code=1)


# ------------------------------------------------------------------ dep graph

def _deps_met(t, tasks) -> bool:
    # A dep that no longer exists was dropped deliberately; it can never
    # complete, so treating it as unmet would block the task forever.
    return all(tasks[d].status == "done" for d in t.deps if d in tasks)


def _unmet(t, tasks) -> list[str]:
    return [d for d in t.deps if d in tasks and tasks[d].status != "done"]


def _cycle(tasks) -> list[str] | None:
    """Return one dependency cycle, or None. `dep` refuses to create one, but a
    hand-edited file or a --force can, and a cycle silently empties the ready
    set - the one failure that would quietly stall the fleet."""
    color: dict[str, int] = {}
    stack: list[str] = []

    def visit(n):
        color[n], _ = 1, stack.append(n)
        for d in tasks[n].deps:
            if d not in tasks:
                continue
            if color.get(d, 0) == 1:
                return [*stack[stack.index(d):], d]
            if color.get(d, 0) == 0 and (r := visit(d)):
                return r
        color[n] = 2
        stack.pop()
        return None

    for n in tasks:
        if color.get(n, 0) == 0 and (r := visit(n)):
            return r
    return None


def _ready(tasks) -> list:
    return sorted((t for t in tasks.values()
                   if t.status == "todo" and _deps_met(t, tasks)),
                  key=lambda t: _aware(t.updated))


def _is_stale(t) -> bool:
    """Blocked ages too. A task blocked on something only a human can decide is
    the one kind the orchestrator cannot resolve itself, so elapsed time is the
    only signal that it needs escalating rather than waiting."""
    return t.status in ("todo", "blocked") and _days(t.updated) >= STALE_DAYS


def _stale(tasks) -> list:
    return [t for t in tasks.values() if _is_stale(t)]


# --------------------------------------------------------------------- verify

def _store_dir(store) -> str:
    return os.path.dirname(os.path.abspath(store.path)) or "."


def _resolve_cwd(raw: str, store) -> str:
    """Where a task's work and its verification happen. A relative path is
    relative to the store, which is what the store-directory default already
    meant; `~` is kept in the record so it stays readable and portable."""
    p = os.path.expanduser(raw)
    return p if os.path.isabs(p) else os.path.join(_store_dir(store), p)


def _need_dir(path: str, exit_code: int):
    """A verify that runs in the wrong tree can pass by accident, so a missing
    directory is a loud error rather than a silent fall back to the store."""
    if not os.path.isdir(path):
        raise df.AxiError(f"no such directory: {df.collapse_home(path)}", "NO_SUCH_CWD",
                          [f"Run `{PROG} list --fields id,cwd` to see where tasks point"],
                          exit_code=exit_code)
    return path


def _run_verify(cmd: str, cwd: str, timeout: int):
    """Returns (ok, exit_code, output_tail). The verify string is a command the
    store's own operator authored, so it runs through the shell as written."""
    try:
        p = subprocess.run(cmd, shell=True, cwd=cwd, capture_output=True,
                           text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return False, None, f"timed out after {timeout}s"
    tail = "\n".join((p.stdout + p.stderr).splitlines()[-TAIL_LINES:])
    return p.returncode == 0, p.returncode, tail


# -------------------------------------------------------------------- commands

def cmd_init(args) -> int:
    path = args.file or STORE
    d = os.path.dirname(os.path.abspath(path))
    stem = os.path.basename(path)[:-6] if path.endswith(".jsonl") else os.path.basename(path)
    target = os.path.join(d, f"schema-{stem}.yaml")
    existing = df.find_contract(path)
    if existing:                                        # 6: idempotent
        df.emit({"contract": df.collapse_home(os.path.abspath(existing)),
                 "status": "unchanged",
                 "help": [f"Run `{PROG} add \"<title>\" --verify \"<cmd>\"` to create a task"]})
        return 0
    with open(target, "w", encoding="utf-8") as f:
        f.write(CONTRACT)
    df.emit({"contract": df.collapse_home(target), "status": "created",
             "store": path,
             "help": [f"Run `{PROG} add \"<title>\" --verify \"<cmd>\"` to create the first task"]})
    return 0


def _identity() -> dict:
    """10: name the tool before the live data, so an agent that met this output
    in a session hook knows what produced it and how to run it again."""
    return {"bin": df.collapse_home(os.path.abspath(__file__)),
            "description": DESCRIPTION,
            "version": VERSION}


def cmd_home(args) -> int:
    out = _identity()
    if not df.find_contract(args.file or STORE):
        # 5: directory-scoped and definitive. An error here would make the
        # session hook shout in every unrelated repository.
        out["tasks"] = f"no task store in {df.collapse_home(os.getcwd())}"
        out["help"] = [f"Run `{PROG} init` to create one here"]
        df.emit(out)
        return 0
    store = _open(args)
    tasks, bad = store.load()
    if not tasks:                                       # 5: definitive empty
        out["tasks"] = "0 of 0 total"
        out["store"] = store.path
        out["help"] = [f"Run `{PROG} add \"<title>\" --verify \"<cmd>\"` "
                       f"to create the first task"]
        df.emit(out)
        return 0

    by = {s: [t for t in tasks.values() if t.status == s] for s in STATUSES}
    ready, stale = _ready(tasks), _stale(tasks)
    clipped = False

    # In flight first: a cold-starting session asks "where did I leave off?"
    # before it asks "what is next?".
    if by["doing"]:
        out["doing"] = [{"id": t.id, "owner": t.owner or "-", "age": _age(t.updated)}
                        for t in sorted(by["doing"], key=lambda t: _aware(t.updated))]
    if ready:
        rows = []
        for t in ready[:HOME_LIMIT]:
            title, full = df.truncate(t.title, CELL)
            clipped = clipped or full is not None
            rows.append({"id": t.id, "title": title})
        out["ready"] = rows
    if by["blocked"]:
        # Oldest first, with age: nothing else in the store reveals that a
        # reason has been waiting for an answer since last month.
        rows = []
        for t in sorted(by["blocked"], key=lambda t: _aware(t.updated)):
            reason, full = df.truncate(t.reason or "-", CELL)
            clipped = clipped or full is not None
            rows.append({"id": t.id, "reason": reason, "age": _age(t.updated)})
        out["blocked"] = rows

    out["counts"] = [{"doing": len(by["doing"]), "ready": len(ready),
                      "todo": len(by["todo"]), "done": len(by["done"]),
                      "blocked": len(by["blocked"]), "stale": len(stale)}]

    open_n = len(by["todo"]) + len(by["doing"]) + len(by["blocked"])
    if not ready and open_n:                            # 5: name the cause
        cycle = _cycle(tasks)
        if cycle:
            out["cause"] = "dependency cycle: no task can ever become ready"
            out["cycle"] = cycle
        elif not by["todo"]:
            out["cause"] = (f"nothing queued: {len(by['doing'])} in flight, "
                            f"{len(by['blocked'])} blocked")
        else:
            out["cause"] = f"every queued task is waiting on deps ({len(by['blocked'])} blocked)"
    if bad:
        out["unreadable_lines"] = len(bad)

    help_lines = []
    if len(ready) > HOME_LIMIT:                 # 9: reveal the cap, do not encode it
        help_lines.append(f"Run `{PROG} list --status todo` to see all "
                          f"{len(ready)} ready tasks")
    if out.get("cycle"):        # a cycle stalls the whole queue: lead with it
        help_lines.append(f"Run `{PROG} dep --help`; break the cycle by dropping "
                          f"and re-adding {out['cycle'][0]} without its dep")
    if ready:
        help_lines.append(f"Run `{PROG} start {ready[0].id} --owner <minion>` "
                          f"to dispatch the next task")
    if by["doing"]:
        help_lines.append(f"Run `{PROG} show {by['doing'][0].id}` for what a minion is holding")
    if by["blocked"]:
        help_lines.append(f"Run `{PROG} list --status blocked` for what is stuck")
    if stale and len(help_lines) < 3:
        help_lines.append(f"Run `{PROG} list --stale` for {len(stale)} tasks "
                          f"untouched over {STALE_DAYS}d")
    if clipped:                                 # 3: name the escape hatch
        help_lines.append(f"Run `{PROG} show <id>` for untruncated values")
    if not help_lines:
        help_lines.append(f"Run `{PROG} add \"<title>\" --verify \"<cmd>\"` to queue more work")
    out["help"] = help_lines[:3]
    df.emit(out)
    return 0


def cmd_add(args) -> int:
    store = _open(args)
    tasks, _ = store.load()
    missing = [d for d in args.dep if d not in tasks]
    if missing:
        raise df.AxiError(f"unknown dependency: {', '.join(missing)}", "UNKNOWN_DEP",
                          [f"Run `{PROG} list` to see task ids"], exit_code=2)
    if args.cwd:
        _need_dir(_resolve_cwd(args.cwd, store), 2)
    rid = _slug(args.title, tasks)
    store.put({"id": rid, "title": args.title, "status": "todo",
               "verify": args.verify, "verify_kind": "prose" if args.prose else "cmd",
               "deps": args.dep, "context": args.context,
               "project": args.project or None, "cwd": args.cwd,
               "base": args.base or None,
               "updated": _now()})
    ready = not args.dep or all(tasks[d].status == "done" for d in args.dep)
    df.emit({"id": rid, "status": "todo", "ready": ready,
             "help": [f"Run `{PROG} start {rid} --owner <minion>` to dispatch it" if ready
                      else f"Run `{PROG} show {rid}` to see what it is waiting on"]})
    return 0


def cmd_show(args) -> int:
    store = _open(args)
    tasks, _ = store.load()
    t = tasks.get(args.id) or _need(store, args.id)
    rec = t.model_dump(mode="json")
    clipped = None
    if not args.full:
        rec["verify"], clipped = df.truncate(rec["verify"], df.DETAIL_TRUNCATE)
        if clipped:
            rec["verify_length"] = clipped
    out = {"task": rec}
    unmet = _unmet(t, tasks)
    out["ready"] = t.status == "todo" and not unmet
    if unmet:
        out["unmet_deps"] = unmet
    hint = {
        "todo": f"Run `{PROG} start {t.id} --owner <minion>` to dispatch it",
        "doing": f"Run `{PROG} done {t.id}` when the work verifies",
        "blocked": f"Run `{PROG} unblock {t.id}` once the blocker is cleared",
        "done": f"Run `{PROG}` for the next ready task",
    }[t.status]
    # 3: name the escape hatch only when there is something behind it
    out["help"] = ([f"Run `{PROG} show {t.id} --full` for the complete verify", hint]
                   if clipped else [hint])
    df.emit(out)
    return 0


def cmd_list(args) -> int:
    store = _open(args)
    if args.fields:                     # 6: a usage error must not read the log
        fields = [f.strip() for f in args.fields.split(",") if f.strip()]
        unknown = [f for f in fields if f not in store.model.model_fields]
        if unknown:
            raise df.AxiError(
                f"unknown field(s): {', '.join(unknown)}", "USAGE_ERROR",
                [f"Valid fields: {', '.join(store.model.model_fields)}"], exit_code=2)
    else:
        fields = list(LIST_FIELDS)      # 2: the smallest schema that decides

    tasks, bad = store.load()
    rows = list(tasks.values())
    total = len(rows)
    if args.status:
        rows = [t for t in rows if t.status == args.status]
    if args.project:
        rows = [t for t in rows if t.project == args.project]
    if args.stale:
        rows = [t for t in rows if _is_stale(t)]
    rows.sort(key=lambda t: (STATUSES.index(t.status), _aware(t.updated)))
    shown = rows[:args.limit]

    cells, clipped = [], False
    for t in shown:
        d = t.model_dump(mode="json")
        row = {}
        for f in fields:
            v = d.get(f)
            if not df._is_scalar(v):    # deps/context would break the TOON table
                v = json.dumps(v, ensure_ascii=False, separators=(",", ":"))
            v, full = df.truncate(v, CELL)
            clipped = clipped or full is not None
            row[f] = v
        cells.append(row)

    out = {"count": f"{len(shown)} of {total} total"}    # 4: aggregate
    if cells:
        out["tasks"] = cells
    if bad:
        out["unreadable_lines"] = len(bad)

    if not shown:
        help_lines = [f"Run `{PROG} list` without filters to see all {total}"]
    else:
        detail = "for one task with all fields"
        help_lines = [f"Run `{PROG} show <id>` {'untruncated' if clipped else detail}"]
        if len(shown) == args.limit and args.limit < len(rows):   # 9: reveal the cap
            help_lines.append(f"Run `{PROG} list --limit {len(rows)}` "
                              f"for all {len(rows)} matches")
    out["help"] = help_lines
    df.emit(out)
    return 0


def cmd_start(args) -> int:
    store = _open(args)
    tasks, _ = store.load()
    t = tasks.get(args.id) or _need(store, args.id)
    # Where the work happens can only be known at dispatch: a minion isolated in its
    # own worktree verifies there, not in the shared tree the task was written
    # against. Omitting --cwd keeps whatever the task already carries.
    if args.cwd:
        _need_dir(_resolve_cwd(args.cwd, store), 2)
    cwd = args.cwd or t.cwd
    if t.status == "doing" and t.owner == args.owner:   # 6: idempotent
        # Same minion, new directory, is a redispatch elsewhere, not a no-op. Letting
        # it pass silently would leave the task verifying in the tree it was retargeted
        # away from, which is the false green this field exists to prevent.
        if cwd != t.cwd:
            _save(store, t, cwd=cwd)
        df.emit({"id": t.id, "status": "doing", "owner": t.owner, "cwd": cwd,
                 "result": "unchanged" if cwd == t.cwd else "retargeted",
                 "help": [f"Run `{PROG} done {t.id}` when the work verifies"]})
        return 0
    _guard_in_flight(t, args.force, f"start {args.id} --owner {args.owner}")
    if t.status == "done":
        raise df.AxiError(f"{t.id} is already done", "INVALID_TRANSITION",
                          [f"Run `{PROG} show {t.id}` to see it"], exit_code=1)
    unmet = _unmet(t, tasks)
    if unmet and not args.force:
        raise df.AxiError(f"{t.id} has {len(unmet)} unmet dependency(ies)", "DEPS_UNMET",
                          [f"Run `{PROG} show {t.id}` to see them"],
                          exit_code=1, extra={"unmet_deps": unmet})
    _save(store, t, status="doing", owner=args.owner, reason=None, cwd=cwd)
    df.emit({"id": t.id, "status": "doing", "owner": args.owner, "cwd": cwd,
             "verify_kind": t.verify_kind,
             "help": [f"Run `{PROG} done {t.id}` when the work verifies",
                      f"Run `{PROG} block {t.id} --reason \"<why>\"` if it cannot proceed"]})
    return 0


def cmd_done(args) -> int:
    store = _open(args)
    t = _need(store, args.id)
    if t.status == "done":                              # 6: idempotent, no rerun
        df.emit({"id": t.id, "status": "done", "result": "unchanged",
                 "help": [f"Run `{PROG}` for the next ready task"]})
        return 0
    if t.status == "blocked":
        raise df.AxiError(f"{t.id} is blocked: {t.reason or 'no reason recorded'}",
                          "INVALID_TRANSITION",
                          [f"Run `{PROG} unblock {t.id}` first"], exit_code=1)

    if args.force:
        if not args.reason:
            raise df.AxiError("--force requires --reason", "REASON_REQUIRED",
                              [f"Run `{PROG} done {t.id} --force --reason \"<why>\"`"],
                              exit_code=2)
        _save(store, t, status="done", reason=args.reason)
        df.emit({"id": t.id, "status": "done", "verified": False,
                 "reason": args.reason,
                 "help": [f"Run `{PROG}` for the next ready task"]})
        return 0

    if t.verify_kind == "prose":
        # Prose is deliberately more work than a command: the friction is the
        # pressure toward machine-checkable verification.
        if not args.reason:
            raise df.AxiError("this task verifies by prose criterion", "REASON_REQUIRED",
                              [f"Run `{PROG} done {t.id} --reason \"<how it is satisfied>\"`"],
                              exit_code=2, extra={"criterion": df.truncate(t.verify, CELL)[0]})
        _save(store, t, status="done", reason=args.reason)
        df.emit({"id": t.id, "status": "done", "verified": "asserted",
                 "help": [f"Run `{PROG}` for the next ready task"]})
        return 0

    cwd = _need_dir(_resolve_cwd(t.cwd, store), 1) if t.cwd else _store_dir(store)
    ok, code, tail = _run_verify(t.verify, cwd, args.timeout)
    if not ok:
        shown, full = df.truncate(tail, df.DETAIL_TRUNCATE)
        extra = {"command": df.truncate(t.verify, CELL)[0], "exit_code": code,
                 "output": shown}
        if full:                        # 3: never omit silently, show the size
            extra["output_length"] = full
        raise df.AxiError(f"verify failed for {t.id}", "VERIFY_FAILED",
                          [f"Run `{PROG} block {t.id} --reason \"<why>\"` if it cannot proceed",
                           f"Run `{PROG} done {t.id} --force --reason \"<why>\"` to override"],
                          exit_code=1, extra=extra)
    _save(store, t, status="done", reason=None)
    df.emit({"id": t.id, "status": "done", "verified": True,
             "help": [f"Run `{PROG}` for the next ready task"]})
    return 0


def cmd_block(args) -> int:
    store = _open(args)
    t = _need(store, args.id)
    if t.status == "blocked" and t.reason == args.reason:
        df.emit({"id": t.id, "status": "blocked", "result": "unchanged",
                 "help": [f"Run `{PROG} unblock {t.id}` once the blocker is cleared"]})
        return 0
    if t.status == "done":
        raise df.AxiError(f"{t.id} is already done", "INVALID_TRANSITION",
                          [f"Run `{PROG} show {t.id}` to see it"], exit_code=1)
    _save(store, t, status="blocked", reason=args.reason)
    df.emit({"id": t.id, "status": "blocked", "reason": args.reason,
             "help": [f"Run `{PROG} add \"<title>\" --verify \"<cmd>\"` then "
                      f"`{PROG} dep {t.id} --on <new-id>` to queue the unblocker"]})
    return 0


def _to_todo(store, t, *, clear_owner: bool, reason: str | None = None):
    return _save(store, t, status="todo", reason=reason,
                 owner=None if clear_owner else t.owner)


def cmd_unblock(args) -> int:
    store = _open(args)
    tasks, _ = store.load()
    t = tasks.get(args.id) or _need(store, args.id)
    if t.status == "todo":
        df.emit({"id": t.id, "status": "todo", "result": "unchanged",
                 "help": [f"Run `{PROG} start {t.id} --owner <minion>` to dispatch it"]})
        return 0
    if t.status != "blocked":
        raise df.AxiError(f"{t.id} is {t.status}, not blocked", "INVALID_TRANSITION",
                          [f"Run `{PROG} show {t.id}` to see it"], exit_code=1)
    _to_todo(store, t, clear_owner=False)
    unmet = _unmet(t, tasks)
    df.emit({"id": t.id, "status": "todo", "ready": not unmet,
             "help": [f"Run `{PROG} start {t.id} --owner <minion>` to dispatch it" if not unmet
                      else f"Run `{PROG} show {t.id}` to see what it is waiting on"]})
    return 0


def cmd_reset(args) -> int:
    """Orphan reaper: the orchestrator died mid-flight and the fleet is gone."""
    store = _open(args)
    t = _need(store, args.id)
    if t.status == "todo":
        df.emit({"id": t.id, "status": "todo", "result": "unchanged",
                 "help": [f"Run `{PROG} start {t.id} --owner <minion>` to dispatch it"]})
        return 0
    if t.status == "done":
        raise df.AxiError(f"{t.id} is done; reset would discard a verified result",
                          "INVALID_TRANSITION",
                          [f"Run `{PROG} show {t.id}` to see it"], exit_code=1)
    prior = t.owner
    # Keep the reason on the record: it is why this is back in the queue, and
    # `start` clears it on redispatch, so it never outlives its usefulness.
    _to_todo(store, t, clear_owner=True, reason=args.reason)
    df.emit({"id": t.id, "status": "todo", "reclaimed_from": prior or "-",
             "reason": args.reason,
             "help": [f"Run `{PROG} start {t.id} --owner <minion>` to redispatch it"]})
    return 0


def cmd_dep(args) -> int:
    store = _open(args)
    tasks, _ = store.load()
    t = tasks.get(args.id) or _need(store, args.id)
    if args.on not in tasks:
        raise df.AxiError(f"unknown dependency: {args.on}", "UNKNOWN_DEP",
                          [f"Run `{PROG} list` to see task ids"], exit_code=2)
    if args.on == args.id:
        raise df.AxiError(f"{args.id} cannot depend on itself", "DEP_CYCLE", exit_code=2)
    if args.on in t.deps:
        df.emit({"id": t.id, "deps": t.deps, "result": "unchanged",
                 "help": [f"Run `{PROG} show {t.id}` to see it"]})
        return 0
    _guard_in_flight(t, args.force, f"dep {args.id} --on {args.on}")

    probe = dict(tasks)
    deps = [*t.deps, args.on]
    probe[t.id] = t.model_copy(update={"deps": deps})
    if cycle := _cycle(probe):
        raise df.AxiError(f"{args.on} -> {args.id} would create a dependency cycle",
                          "DEP_CYCLE", [f"Run `{PROG} show {args.on}` to see its deps"],
                          exit_code=2, extra={"cycle": cycle})

    _save(store, t, deps=deps)
    df.emit({"id": t.id, "deps": deps, "ready": not _unmet(probe[t.id], tasks),
             "help": [f"Run `{PROG} show {t.id}` to see what it is waiting on"]})
    return 0


def cmd_drop(args) -> int:
    store = _open(args)
    t = store.get(args.id)
    if t is None:                                       # 6: idempotent no-op
        df.emit({"id": args.id, "result": "absent",
                 "help": [f"Run `{PROG} list` to see task ids"]})
        return 0
    _guard_in_flight(t, args.force, f"drop {args.id}")
    # Write the reason first: delete only appends a tombstone, so this is what
    # keeps "why" recoverable from the raw log after the record is gone.
    _save(store, t, reason=args.reason)
    store.delete(args.id)
    df.emit({"id": args.id, "result": "dropped", "reason": args.reason,
             "help": [f"Run `{PROG}` for the current queue"]})
    return 0


# ------------------------------------------------ session integrations (§7)

def _is_managed(hook: dict) -> bool:
    return AMBIENT_FLAG in (hook.get("command") or "")


def _hook_update(settings: dict, command: str) -> tuple[dict, str]:
    """Claude Code and Codex share the hooks.SessionStart group shape."""
    updated = json.loads(json.dumps(settings))
    if not isinstance(updated.get("hooks"), dict):
        updated["hooks"] = {}
    hooks = updated["hooks"]
    if not isinstance(hooks.get("SessionStart"), list):
        hooks["SessionStart"] = []

    for group in hooks["SessionStart"]:
        for hook in group.get("hooks") or []:
            if not _is_managed(hook):
                continue
            if (hook.get("command") == command and hook.get("type") == "command"
                    and hook.get("timeout") == HOOK_TIMEOUT):
                return settings, "unchanged (no-op)"
            hook.update(type="command", command=command, timeout=HOOK_TIMEOUT)
            return updated, "repaired"      # 7: path repair after a reinstall

    hooks["SessionStart"].append({"matcher": "", "hooks": [
        {"type": "command", "command": command, "timeout": HOOK_TIMEOUT}]})
    return updated, "installed"


def _hook_removal(settings: dict) -> tuple[dict, bool]:
    updated = json.loads(json.dumps(settings))
    hooks = updated.get("hooks")
    if not isinstance(hooks, dict) or not isinstance(hooks.get("SessionStart"), list):
        return settings, False
    changed, remaining = False, []
    for group in hooks["SessionStart"]:
        inner = [h for h in (group.get("hooks") or []) if not _is_managed(h)]
        if len(inner) != len(group.get("hooks") or []):
            changed = True
            if not inner:
                continue
            group = {**group, "hooks": inner}
        remaining.append(group)
    if not changed:
        return settings, False
    if remaining:
        hooks["SessionStart"] = remaining
    else:
        hooks.pop("SessionStart", None)
    if not hooks:
        updated.pop("hooks", None)
    return updated, True


def _opencode_plugin(argv: list[str]) -> str:
    """OpenCode has no SessionStart hook, so the home view is injected as
    ambient system context instead, cached once per session."""
    return f"""// {OPENCODE_PREFIX} {TOOL_NAME}
// Generated by tasks.py. Safe to edit only if you remove the marker above.
import {{ spawn }} from "node:child_process";

const argv = {json.dumps(argv)};
const header = {json.dumps(f"## AXI ambient context: {TOOL_NAME}")};
const timeoutMs = {HOOK_TIMEOUT * 1000};

function runHomeView(cwd) {{
  return new Promise((resolve) => {{
    const child = spawn(argv[0], argv.slice(1), {{
      cwd: cwd || process.cwd(), env: process.env, shell: false,
      stdio: ["ignore", "pipe", "pipe"],
    }});
    let stdout = "", settled = false;
    const done = (v) => {{ if (!settled) {{ settled = true; clearTimeout(timer); resolve(v); }} }};
    const timer = setTimeout(() => {{ child.kill("SIGTERM"); done(""); }}, timeoutMs);
    child.stdout?.setEncoding("utf-8");
    child.stdout?.on("data", (c) => {{ stdout += c; }});
    child.on("error", () => done(""));
    child.on("close", (code) => done(code === 0 ? stdout.trim() : ""));
  }});
}}

export const agentTasksAmbientContext = async ({{ directory }}) => {{
  const cache = new Map();
  return {{
    "experimental.chat.system.transform": async (input, output) => {{
      const id = input.sessionID ?? "__global__";
      let view = cache.get(id);
      if (view === undefined) {{ view = await runHomeView(directory); cache.set(id, view); }}
      if (view.length === 0) return;
      output.system.push(header + "\n" + view);
    }},
  }};
}};
"""


def _opencode_path(t: dict) -> str:
    return os.path.join(t["opencode"], f"axi-{TOOL_NAME}.js")


def cmd_ambient(args) -> int:
    """The session-hook entry point. Silent where there is no store, and never
    non-zero: a task manager must not be able to break a session start."""
    if not df.find_contract(args.file or STORE):
        return 0
    try:
        cmd_home(args)
    except (df.AxiError, df.ContractError, OSError) as e:
        df.emit({"error": str(e), "code": "AMBIENT_DEGRADED",
                 "help": [f"Run `{PROG}` here to see the full error"]})
    return 0


def cmd_setup(args) -> int:
    uv = shutil.which("uv")
    if not uv:
        raise df.AxiError("uv not found on PATH", "SETUP_ERROR",
                          [f"Install uv, then re-run `{PROG} setup`"], exit_code=1)
    me = os.path.abspath(__file__)
    argv = [*df._hook_argv(uv, me), AMBIENT_FLAG]
    command = " ".join(argv)
    t = df._hook_targets(args.scope)
    apps = ["claude", "codex", "opencode"] if args.app == "all" else [args.app]
    rows, extra = [], {}

    def status_of(app: str) -> str:
        if app == "opencode":
            head = (df._read_text(_opencode_path(t)) or "").split("\n", 1)[0]
            return "installed" if OPENCODE_PREFIX in head else "absent"
        groups = (df._read_json(t[app]).get("hooks") or {}).get("SessionStart") or []
        found = any(_is_managed(h) for g in groups for h in (g.get("hooks") or []))
        return "installed" if found else "absent"

    if args.status:
        for app in apps:
            path = _opencode_path(t) if app == "opencode" else t[app]
            rows.append({"app": app, "status": status_of(app),
                         "path": df.collapse_home(path)})
        stale = df.codex_config_update(df._read_text(t["codex_config"]) or "")[1]
        df.emit({"scope": args.scope, "targets": rows,
                 "codex_hooks_feature": "disabled" if stale else "enabled",
                 "help": [f"Run `{PROG} setup` to install",
                          f"Run `{PROG} setup --uninstall` to remove"]})
        return 0

    for app in apps:
        if app == "opencode":
            path = _opencode_path(t)
            if args.uninstall:
                status = "already absent (no-op)"
                if status_of("opencode") != "absent":
                    os.unlink(path)
                    status = "removed"
            else:
                want, have = _opencode_plugin(argv), df._read_text(path)
                if have == want:                        # 7: idempotent
                    status = "unchanged (no-op)"
                else:
                    df._write(path, want)
                    status = "repaired" if have else "installed"
            rows.append({"app": app, "status": status, "path": df.collapse_home(path)})
            continue

        data = df._read_json(t[app])
        if args.uninstall:
            updated, ch = _hook_removal(data)
            status = "removed" if ch else "already absent (no-op)"
        else:
            updated, status = _hook_update(data, command)
        if not status.endswith("(no-op)"):
            df._write(t[app], json.dumps(updated, indent=2) + "\n")
        rows.append({"app": app, "status": status, "path": df.collapse_home(t[app])})

        if app == "codex" and not args.uninstall:
            # Repo-level Codex hooks still need the user-level feature flag.
            cfg = t["codex_config"]
            new, ch = df.codex_config_update(df._read_text(cfg) or "")
            if ch:
                df._write(cfg, new)
            extra["codex_hooks_feature"] = (
                f"enabled in {df.collapse_home(cfg)}" if ch
                else f"already enabled in {df.collapse_home(cfg)}")

    out = {"scope": args.scope, "command": command, "targets": rows}
    out.update(extra)
    out["help"] = ([f"Run `{PROG} setup --status` to verify"] if args.uninstall else
                   [f"Run `{PROG} setup --status` to verify",
                    f"Run `{PROG} setup --uninstall` to remove",
                    f"Run `{PROG} skill --install` for the on-demand skill instead"])
    df.emit(out)
    return 0


# --------------------------------------------------- installable skill (§7)

def render_skill() -> str:
    """Generated from the parser, so the skill cannot drift from the CLI. Static
    by construction: it names no store, no task, and no machine-specific path."""
    _parser, reg = build_parser()
    body = [
        "---",
        f"name: {SKILL_NAME}",
        "description: >-",
    ]
    row = ""
    for w in SKILL_TRIGGER.split():
        if len(row) + len(w) + 1 > 76:
            body.append(f"  {row}")
            row = w
        else:
            row = f"{row} {w}".strip()
    body += [f"  {row}", "---", "", f"# {SKILL_NAME}", "", DESCRIPTION + ".", "",
             "## Ownership", "",
             "One orchestrator creates tasks and dispatches them. Each worker updates",
             "only the task it owns. A task in `doing` belongs to its owner, and the",
             "orchestrator treats it as read-only; ownership transfers on `start` and",
             "returns on any terminal transition. Workers never create tasks: a worker",
             "that finds new work runs `block`, and the orchestrator queues the",
             "unblocker and wires it with `dep`.", "",
             "## Verification", "",
             "Every task carries a `--verify` command that `done` runs; a non-zero exit",
             "refuses the transition. `--prose` marks a criterion asserted instead, and",
             "`done` then requires `--reason`. `--force --reason` overrides either and",
             "records why, so a forced completion stays distinguishable from a verified",
             "one.", "",
             "## Commands", "",
             f"Run `{PROG} <command> --help` for the full reference on any of these.", ""]
    for name, sp in reg.items():
        usage = " ".join(sp.format_usage().split()).replace("usage: ", "").replace(" [-h]", "")
        body += [f"### {name}", "", sp.description or "", "", "```sh", usage, "```", ""]
    body += ["## Output", "",
             "TOON on stdout, including errors; nothing is written to stderr.",
             "Exit 0 is success including idempotent no-ops, 1 means the request",
             "could not be satisfied, 2 is a usage or contract error.", ""]
    return "\n".join(body)


def _skill_path(scope: str, app: str) -> str:
    root = os.path.expanduser("~") if scope == "user" else os.getcwd()
    return os.path.join(root, *SKILL_APPS[app], SKILL_NAME, "SKILL.md")


def _skill_place(path: str, want: str, args) -> str:
    if args.uninstall:
        have = df._read_text(path)
        if have is None:
            return "already absent (no-op)"
        if f"name: {SKILL_NAME}" not in have:
            raise df.AxiError(
                f"{df.collapse_home(path)} was not generated by this tool",
                "SKILL_FOREIGN", ["Remove it by hand if you are sure"], exit_code=1)
        os.unlink(path)
        with contextlib.suppress(OSError):
            os.rmdir(os.path.dirname(path))
        return "removed"
    have = df._read_text(path)
    if have == want:
        return "unchanged (no-op)"
    df._write(path, want)
    return "regenerated" if have else "installed"


def cmd_skill(args) -> int:
    if args.out and args.install:
        raise df.AxiError("--out and --install choose different destinations",
                          "USAGE_ERROR",
                          [f"Run `{PROG} skill --install` to install it for an agent",
                           f"Run `{PROG} skill --out <path>` to write a copy"],
                          exit_code=2)
    want = render_skill()

    if args.install or args.uninstall:
        apps = list(SKILL_APPS) if args.app == "all" else [args.app]
        rows = [{"app": a, "status": _skill_place(_skill_path(args.scope, a), want, args),
                 "path": df.collapse_home(os.path.dirname(_skill_path(args.scope, a)))}
                for a in apps]
        df.emit({"scope": args.scope, "targets": rows,
                 "help": ([f"Run `{PROG} skill --install` to reinstall"] if args.uninstall
                          else [f"Restart your agent session to pick up {SKILL_NAME}",
                                f"Run `{PROG} skill --uninstall` to remove it"])})
        return 0

    out = args.out or SKILL_PATH
    have = df._read_text(out)

    if args.check:                      # 7: CI gate against a stale skill
        if have is None:
            raise df.AxiError(f"{out} does not exist", "SKILL_STALE",
                              [f"Run `{PROG} skill` to generate it"], exit_code=1)
        if have != want:
            raise df.AxiError(f"{out} is out of date", "SKILL_STALE",
                              [f"Run `{PROG} skill` to regenerate it"], exit_code=1)
        df.emit({"skill": f"{out} is up to date"})
        return 0

    if have == want:
        df.emit({"skill": f"{df.collapse_home(out)} unchanged (no-op)"})
        return 0
    df._write(out, want)
    df.emit({"skill": f"{'regenerated' if have else 'generated'} {df.collapse_home(out)}",
             "lines": len(want.splitlines()),
             "help": [f"Run `{PROG} skill --install` to install it for your agents",
                      f"Run `{PROG} skill --check` in CI to fail on a stale skill"]})
    return 0


